"""Authenticated WSGI bridge for ChatGPT Actions and other approved clients.

The bridge delegates natural-language consultation to explicitly configured
ModelHub providers. It does not claim that the synthetic LIF runtime is a
biologically validated Drosophila brain or that language is generated by a
biological connectome simulation.
"""
from __future__ import annotations
import hmac
import json
import os
from pathlib import Path
from wsgiref.simple_server import make_server
from .model_hub import ModelConsultation

class FlyBrainChatApp:
    def __init__(self, token: str, ledger_path: str | Path = "data/flybrain-chat.sqlite3"):
        if not isinstance(token, str) or len(token) < 32:
            raise ValueError("FLYBRAIN_CHAT_API_TOKEN must contain at least 32 characters")
        self._token = token
        self._consultation = ModelConsultation(ledger_path)

    @staticmethod
    def _response(start_response, status: str, payload: dict):
        body = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
        start_response(status, [
            ("Content-Type", "application/json; charset=utf-8"),
            ("Content-Length", str(len(body))),
            ("Cache-Control", "no-store"),
            ("X-Content-Type-Options", "nosniff"),
        ])
        return [body]

    def __call__(self, environ, start_response):
        method = environ.get("REQUEST_METHOD", "GET").upper()
        path = environ.get("PATH_INFO", "")
        if method == "GET" and path == "/health":
            return self._response(start_response, "200 OK", {
                "status": "ok", "service": "flybrain-chat-bridge",
                "version": "0.13.3", "authentication_required_for_queries": True,
            })
        auth = environ.get("HTTP_AUTHORIZATION", "")
        supplied = auth[7:] if auth.startswith("Bearer ") else ""
        if not hmac.compare_digest(supplied, self._token):
            return self._response(start_response, "401 Unauthorized", {"error": "unauthorized"})
        if method == "POST" and path == "/v1/ask":
            try:
                length = int(environ.get("CONTENT_LENGTH") or "0")
                if length < 1 or length > 32768:
                    return self._response(start_response, "413 Payload Too Large", {"error": "request body must be 1..32768 bytes"})
                raw = environ["wsgi.input"].read(length)
                data = json.loads(raw.decode("utf-8"))
                question = data.get("question") if isinstance(data, dict) else None
                if not isinstance(question, str) or not question.strip() or len(question) > 12000:
                    return self._response(start_response, "400 Bad Request", {"error": "question must be a non-empty string of at most 12000 characters"})
                timeout = data.get("timeout_seconds", 45)
                if isinstance(timeout, bool) or not isinstance(timeout, (int, float)) or not 1 <= timeout <= 120:
                    return self._response(start_response, "400 Bad Request", {"error": "timeout_seconds must be between 1 and 120"})
                result = self._consultation.consult(question.strip(), timeout=int(timeout))
                if result["status"] == "no_providers_configured":
                    return self._response(start_response, "503 Service Unavailable", {
                        "status": result["status"],
                        "message": "No ModelHub provider is configured. Configure a provider model and secret in the hosting environment.",
                        "flybrain_scope": "The connectome and synthetic neural runtime are research tools; they are not a validated natural-language brain model.",
                    })
                completed = [x for x in result.get("results", []) if x.get("status") == "completed"]
                if not completed:
                    return self._response(start_response, "502 Bad Gateway", {
                        "status": "all_providers_failed",
                        "message": "Configured ModelHub providers did not return a usable answer.",
                    })
                return self._response(start_response, "200 OK", {
                    "status": result["status"],
                    "answer_candidates": [{"provider": x["provider"], "model": x["model"], "role": x["role"], "answer": x["response"]} for x in completed],
                    "workflow": result.get("plan", {}).get("workflow", []),
                    "execution_policy": result.get("execution_policy"),
                    "scientific_scope": "FlyBrain-NOS orchestrates research consultation; its synthetic LIF runtime is not biologically validated and is not itself the natural-language answer generator.",
                    "external_data_transfer": result.get("privacy", {}).get("external_data_transfer", False),
                })
            except (UnicodeDecodeError, json.JSONDecodeError, AttributeError, TypeError, ValueError):
                return self._response(start_response, "400 Bad Request", {"error": "invalid_request"})
            except Exception:
                return self._response(start_response, "502 Bad Gateway", {"error": "consultation_failed"})
        return self._response(start_response, "404 Not Found", {"error": "not_found"})

def main():
    token = os.environ.get("FLYBRAIN_CHAT_API_TOKEN", "")
    host = os.environ.get("HOST", "0.0.0.0")
    port = int(os.environ.get("PORT", "10000"))
    ledger = os.environ.get("FLYBRAIN_CHAT_LEDGER", "data/flybrain-chat.sqlite3")
    app = FlyBrainChatApp(token, ledger)
    with make_server(host, port, app) as server:
        server.serve_forever()

if __name__ == "__main__":
    main()
